import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const read = async (file) =>
  JSON.parse(await readFile(new URL(file, root), "utf8"));
const data = await read("content/catalog.json"),
  cooking = await read("content/cooking.json");
const seen = new Set();
for (const r of data.recipes) {
  const key = `${r.chapter}:${r.lap}`;
  if (seen.has(key)) throw Error("Duplicate recipe slot " + key);
  seen.add(key);
  if (
    r.pairs.length !== 3 ||
    r.pairs.some((p) => p.length !== 2) ||
    r.outcomes.length !== 8
  )
    throw Error("Incomplete recipe " + r.id);
  for (const id of [...r.pairs.flat(), ...r.outcomes, r.target])
    if (!data.entities[id]) throw Error("Unknown food " + id);
  if (r.outcomes[0] !== r.target) throw Error("Target mismatch " + r.id);
  if (r.status === "playable")
    for (const id of r.outcomes)
      if (!data.entities[id].file || !cooking.plans[id])
        throw Error("Unfinished playable dish " + id);
}
for (const [id, plan] of Object.entries(cooking.plans)) {
  if (!data.entities[id]) throw Error("Unknown cooking dish " + id);
  if (plan.method !== "oven" && plan.stages.length !== 4)
    throw Error("Incomplete cooking stages " + id);
  for (const stage of plan.stages)
    if (
      !cooking.vessels[stage.vessel] ||
      !["none", "oil", "steam"].includes(stage.effect)
    )
      throw Error("Unknown cooking vessel or effect " + id);
  for (const [locale, copy] of Object.entries(cooking.locales))
    if (
      !Array.isArray(copy.beats[id]) ||
      copy.beats[id].length !== plan.stages.length
    )
      throw Error("Incomplete cooking copy " + locale + "/" + id);
}
for (const [file, global, value] of [
  ["catalog-data", "CookingCatalogData", data],
  ["cooking-data", "CookingData", cooking],
]) {
  const output =
    "(function(root){\n'use strict';\n// Generated by scripts/build-content.mjs. Edit content/ JSON.\nconst data=" +
    JSON.stringify(value, null, 2) +
    ";\nroot." +
    global +
    "=data;\nif(typeof module!=='undefined')module.exports=data;\n})(typeof window!=='undefined'?window:globalThis);\n";
  const path = new URL("dist/" + file + ".js", root);
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== output)
      throw Error("Stale " + file + ": run node scripts/build-content.mjs");
  } else await writeFile(path, output);
}
console.log(
  `Content ${process.argv.includes("--check") ? "checked" : "built"}: ${data.recipes.length} recipes, ${Object.keys(data.entities).length} food IDs, ${Object.keys(cooking.plans).length} cooking plans`,
);
